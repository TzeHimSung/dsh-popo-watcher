import { build, context } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const output = fileURLToPath(new URL('../lib/client.js', import.meta.url))
const options = {
  absWorkingDir: root,
  entryPoints: ['src/client/index.js'], outfile: output,
  bundle: true, format: 'iife', platform: 'browser', target: 'es2022',
  minify: false, charset: 'utf8', legalComments: 'none',
  banner: { js: '// Generated from src/client/index.js. Run npm run build:client; do not edit this file.' },
}

if (process.argv.includes('--watch')) {
  const builder = await context(options)
  await builder.watch()
  console.log('Watching client sources; output: lib/client.js')
  for (const signal of ['SIGINT', 'SIGTERM']) process.once(signal, async () => { await builder.dispose(); process.exit(0) })
} else {
  const result = await build({ ...options, write: false })
  const generated = result.outputFiles[0].contents
  if (process.argv.includes('--check')) {
    let saved
    try { saved = readFileSync(output) } catch { saved = Buffer.alloc(0) }
    if (!saved.equals(Buffer.from(generated))) {
      console.error('lib/client.js differs from source. Run npm run build:client.')
      process.exitCode = 1
    } else console.log('Client bundle matches source.')
  } else {
    writeFileSync(output, generated)
    console.log('Built lib/client.js')
  }
}
